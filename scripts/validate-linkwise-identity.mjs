import assert from 'node:assert/strict';
import { decodeLinkwiseRoute, reconcileLinkwiseOffer, summariseReconciliation } from '../lib/linkwise-identity.mjs';
const URL_OK='https://go.linkwi.se/z/399-0/CD104/?lnkurl=https%3A%2F%2Fwww.shop.gr%2Fproduct%3Ffoo%3Dbar';
const WHEN=new Date('2026-11-07T00:00:00Z');
const base={tracking_url:URL_OK,program_id:'unknown',price_eur:200,in_stock:true,is_active:true,last_seen_at:'2026-11-06T23:00:00Z',valid_to:'2026-11-20T00:00:00Z'};
const programs=[{linkwise_program_id:'399',program_name:'Shop',program_approved:true,percent_commission_min:8}];
const merchants=[{id:'canonical-123',merchant_name:'Shop',canonical_domain:'shop.gr',active:true,program_approved:true,tracking_verified:true}];
const scope={programs,merchants,now:WHEN};
assert.equal(decodeLinkwiseRoute(URL_OK).program_id,'399');
assert.equal(decodeLinkwiseRoute(URL_OK).destination_host,'shop.gr');
assert.equal(decodeLinkwiseRoute(URL_OK).publisher_id,'CD104');
assert.equal(decodeLinkwiseRoute(URL_OK.replace('CD104','CD999')),null);
assert.equal(decodeLinkwiseRoute(URL_OK.replace('go.linkwi.se','go.linkwi.se.evil.tld')),null);
assert.equal(decodeLinkwiseRoute('javascript:alert(1)'),null);
assert.equal(decodeLinkwiseRoute('https://go.linkwi.se/z/399-0/CD104/?lnkurl=javascript:alert(1)'),null);
assert.equal(reconcileLinkwiseOffer(base,scope).status,'READY_FOR_INDEPENDENT_SKEPTIC');
assert.equal(reconcileLinkwiseOffer(base,scope).expected_min_commission_eur,16);
assert.equal(reconcileLinkwiseOffer({...base,program_id:'23'},scope).reasons.includes('PROGRAM_ID_CONFLICT'),true);
assert.equal(reconcileLinkwiseOffer(base,{...scope,programs:[]}).reasons.includes('PROGRAM_NOT_IN_AUTHORITY'),true);
assert.equal(reconcileLinkwiseOffer(base,{...scope,merchants:[]}).reasons.includes('MERCHANT_NOT_CANONICALLY_VERIFIED'),true);
assert.equal(reconcileLinkwiseOffer(base,{...scope,programs:[{...programs[0],program_approved:false}]}).reasons.includes('PROGRAM_APPROVAL_UNKNOWN'),true);
assert.equal(reconcileLinkwiseOffer({...base,in_stock:null},scope).reasons.includes('STOCK_NOT_CONFIRMED'),true);
assert.equal(reconcileLinkwiseOffer({...base,in_stock:false},scope).reasons.includes('OUT_OF_STOCK'),true);
assert.equal(reconcileLinkwiseOffer({...base,last_seen_at:'2026-10-01T00:00:00Z'},scope).reasons.includes('FEED_NOT_FRESH'),true);
assert.equal(reconcileLinkwiseOffer({...base,valid_to:'2026-11-01T00:00:00Z'},scope).reasons.includes('EXPIRED'),true);
assert.equal(reconcileLinkwiseOffer({...base,tracking_url:'https://go.linkwi.se/z/438-0/CD104/?lnkurl=https%3A%2F%2Fshop.gr'},scope).reasons.includes('PROGRAM_ID_CONFLICT'),false);
const report=summariseReconciliation([base,{...base,program_id:'23'}],scope);
assert.equal(report.processed,2);
assert.equal(report.writes,0);
assert.equal(report.byProgram['399'].total,2);
assert.equal(report.reason_counts.PROGRAM_ID_CONFLICT,1);
console.log('Linkwise identity: structural, domain, approval, commission, and stock preflight assertions passed.');
