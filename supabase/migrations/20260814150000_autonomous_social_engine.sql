create or replace function public.claim_social_publish_jobs(p_worker_id text,p_limit integer default 20)
returns setof public.social_publish_jobs
language plpgsql security definer set search_path=public
as $$
begin
  return query
  with picked as (
    select id from public.social_publish_jobs
    where status in ('queued','failed') and next_attempt_at<=now() and attempt_count<5
    order by next_attempt_at,created_at
    for update skip locked
    limit greatest(1,least(coalesce(p_limit,20),100))
  )
  update public.social_publish_jobs j
  set status='processing',worker_id=p_worker_id,attempt_count=j.attempt_count+1,
      started_at=coalesce(j.started_at,now()),updated_at=now(),error=null
  where j.id in (select id from picked)
  returning j.*;
end;
$$;
revoke all on function public.claim_social_publish_jobs(text,integer) from public,anon,authenticated;
grant execute on function public.claim_social_publish_jobs(text,integer) to service_role;
