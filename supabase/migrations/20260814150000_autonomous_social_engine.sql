-- Autonomous affiliate social engine: Postiz-first/Buffer-fallback publishing,
-- public TikTok link-in-bio redirects, click analytics, incidents and provider health.

create table if not exists public.affiliate_redirects (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  product_id uuid references public.products(id) on delete cascade,
  platform text not null check (platform in ('facebook','instagram','tiktok','linkedin')),
  tracking_url_snapshot text not null,
  label text not null,
  merchant_name text,
  price numeric(14,2),
  image_url text,
  active boolean not null default true,
  valid_until timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_affiliate_redirects_active_platform on public.affiliate_redirects(platform, active, created_at desc);

create table if not exists public.affiliate_click_events (
  id bigint generated by default as identity primary key,
  redirect_id uuid references public.affiliate_redirects(id) on delete set null,
  slug text not null,
  platform text,
  referrer text,
  user_agent_hash text,
  request_fingerprint text,
  clicked_at timestamptz not null default now()
);
create index if not exists idx_affiliate_click_events_slug_time on public.affiliate_click_events(slug, clicked_at desc);

create table if not exists public.social_publish_jobs (
  id uuid primary key default gen_random_uuid(),
  calendar_item_id uuid not null unique references public.social_content_calendar(id) on delete cascade,
  platform text not null check (platform in ('facebook','instagram','tiktok','linkedin')),
  preferred_provider text not null default 'auto' check (preferred_provider in ('auto','postiz','buffer')),
  actual_provider text,
  status text not null default 'queued' check (status in ('queued','processing','scheduled','published','failed','cancelled')),
  attempt_count integer not null default 0,
  idempotency_key text not null unique,
  external_post_id text,
  external_url text,
  provider_payload jsonb not null default '{}'::jsonb,
  provider_response jsonb not null default '{}'::jsonb,
  error text,
  worker_id text,
  next_attempt_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_social_publish_jobs_queue on public.social_publish_jobs(status, next_attempt_at, created_at);

create table if not exists public.social_incidents (
  id uuid primary key default gen_random_uuid(),
  severity text not null default 'warning' check (severity in ('info','warning','critical')),
  incident_type text not null,
  platform text,
  provider text,
  entity_type text,
  entity_id text,
  message text not null,
  details jsonb not null default '{}'::jsonb,
  status text not null default 'open' check (status in ('open','acknowledged','resolved')),
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  resolved_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists idx_social_incidents_open on public.social_incidents(status, severity, last_seen_at desc);

create table if not exists public.social_provider_health (
  provider text not null,
  platform text not null,
  configured boolean not null default false,
  healthy boolean not null default false,
  details jsonb not null default '{}'::jsonb,
  checked_at timestamptz not null default now(),
  primary key(provider, platform)
);

create table if not exists public.product_csv_import_batches (
  id uuid primary key default gen_random_uuid(),
  file_name text,
  rows_seen integer not null default 0,
  rows_upserted integer not null default 0,
  rows_rejected integer not null default 0,
  status text not null default 'completed',
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

