create or replace function public.worker_v3_outbox_ack(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid := nullif(p_payload->>'job_id','')::uuid;
  v_status text := lower(coalesce(p_payload->>'status',''));
  v_row public.social_publishing_outbox%rowtype;
begin
  if v_id is null then raise exception 'job_id_required'; end if;
  if v_status not in ('scheduled','published','failed','cancelled','queued') then
    raise exception 'invalid_status';
  end if;

  update public.social_publishing_outbox o
     set status=v_status,
         external_post_id=coalesce(nullif(p_payload->>'external_post_id',''),o.external_post_id),
         external_permalink=coalesce(nullif(p_payload->>'external_permalink',''),o.external_permalink),
         scheduled_at=case when v_status='scheduled' then coalesce(nullif(p_payload->>'scheduled_at','')::timestamptz,o.scheduled_for,now()) else o.scheduled_at end,
         published_at=case when v_status='published' then coalesce(nullif(p_payload->>'published_at','')::timestamptz,now()) else o.published_at end,
         last_error=case when v_status='failed' then nullif(p_payload->>'error','') else null end,
         metadata=o.metadata || coalesce(p_payload->'metadata','{}'::jsonb),
         claimed_by=null,
         claimed_at=null,
         lease_expires_at=null
   where o.id=v_id
   returning o.* into v_row;

  if not found then raise exception 'job_not_found'; end if;
  return to_jsonb(v_row);
end;
$$;

create or replace function public.worker_v3_delivery_metrics_batch(p_rows jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare v_count integer := 0;
begin
  if jsonb_typeof(p_rows) <> 'array' then raise exception 'rows_array_required'; end if;
  insert into public.social_distribution_metrics(outbox_id,provider_key,platform,metric_payload,observed_at)
  select
    case when coalesce(x->>'job_id','') ~* '^[0-9a-f-]{36}$' then (x->>'job_id')::uuid else null end,
    nullif(lower(x->>'provider_key'),''),
    nullif(lower(x->>'platform'),''),
    x,
    coalesce(nullif(x->>'observed_at','')::timestamptz,now())
  from jsonb_array_elements(p_rows) x;
  get diagnostics v_count = row_count;
  return jsonb_build_object('accepted',v_count,'source','vmdb');
end;
$$;

