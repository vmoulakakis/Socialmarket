-- VMDB v16: canonical SocialMarket -> SocialScheduler publishing contract.
-- This replaces the deleted legacy Supabase publishing control plane while keeping
-- SocialScheduler's existing RPC/Edge Function contract stable.

create extension if not exists pgcrypto;

create table if not exists public.social_publishing_outbox (
  id uuid primary key default gen_random_uuid(),
  source_key text not null unique,
  source_presentation_id uuid references public.social_presentation_intelligence(id) on delete set null,
  platform text not null check (platform in ('facebook','instagram','tiktok','linkedin')),
  title text,
  brand_slug text,
  brand_name text,
  caption text not null,
  hashtags jsonb not null default '[]'::jsonb,
  format text not null default 'post',
  media_url text,
  tracking_url text,
  scheduled_for timestamptz not null,
  priority integer not null default 100,
  status text not null default 'queued' check (status in ('queued','leased','scheduled','published','failed','cancelled')),
  provider_key text,
  claimed_by text,
  claimed_at timestamptz,
  lease_expires_at timestamptz,
  external_post_id text,
  external_permalink text,
  scheduled_at timestamptz,
  published_at timestamptz,
  attempt_count integer not null default 0,
  last_error text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists social_publishing_outbox_ready_idx
  on public.social_publishing_outbox(status, scheduled_for, priority, created_at);
create index if not exists social_publishing_outbox_platform_idx
  on public.social_publishing_outbox(platform, status, scheduled_for);
create index if not exists social_publishing_outbox_provider_idx
  on public.social_publishing_outbox(provider_key, status, scheduled_for);

create table if not exists public.social_distribution_metrics (
  id bigint generated by default as identity primary key,
  outbox_id uuid references public.social_publishing_outbox(id) on delete set null,
  provider_key text,
  platform text,
  metric_payload jsonb not null,
  observed_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create or replace function public.social_outbox_touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_social_publishing_outbox_updated_at on public.social_publishing_outbox;
create trigger trg_social_publishing_outbox_updated_at
before update on public.social_publishing_outbox
for each row execute function public.social_outbox_touch_updated_at();

create or replace function public.vmdb_social_outbox_refill(p_hours integer default 72)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inserted integer := 0;
  v_pending integer := 0;
  v_hours integer := greatest(12, least(coalesce(p_hours,72),168));
begin
  insert into public.social_publishing_outbox(
    source_key, source_presentation_id, platform, title, brand_slug, brand_name,
    caption, hashtags, format, media_url, tracking_url, scheduled_for, priority, metadata
  )
  select
    'presentation:' || s.id::text,
    s.id,
    lower(s.platform),
    coalesce(nullif(s.creative_brief->>'title',''), nullif(s.hook,''), 'Approved SocialMarket content'),
    coalesce(nullif(s.creative_brief->>'brand_slug',''),'socialmarket'),
    coalesce(nullif(s.creative_brief->>'brand_name',''),'SocialMarket'),
    coalesce(
      nullif(s.creative_brief->>'caption',''),
      nullif(concat_ws(E'\n\n', nullif(s.hook,''), nullif(s.pain_statement,''), nullif(s.solution_statement,''), nullif(s.value_statement,''), nullif(s.cta,'')),''),
      'Approved SocialMarket content'
    ),
    case when jsonb_typeof(s.creative_brief->'hashtags')='array' then s.creative_brief->'hashtags' else '[]'::jsonb end,
    coalesce(nullif(s.creative_brief->>'format',''),'post'),
    nullif(s.creative_brief->>'media_url',''),
    nullif(s.creative_brief->>'tracking_url',''),
    (s.creative_brief->>'scheduled_for')::timestamptz,
    greatest(1, least(coalesce(nullif(s.creative_brief->>'priority','')::integer,100),1000)),
    jsonb_build_object(
      'vmdb_source','social_presentation_intelligence',
      'confidence',s.confidence,
      'critic_status',s.critic_status,
      'product_candidate_id',s.product_candidate_id,
      'merchant_id',s.merchant_id,
      'problem_cluster_id',s.problem_cluster_id
    )
  from public.social_presentation_intelligence s
  where lower(s.platform) in ('facebook','instagram','tiktok','linkedin')
    and lower(coalesce(s.critic_status,'')) in ('approved','pass','passed','ready')
    and coalesce(s.creative_brief->>'scheduled_for','') ~ '^\d{4}-\d{2}-\d{2}T'
    and (s.creative_brief->>'scheduled_for')::timestamptz > now()
    and (s.creative_brief->>'scheduled_for')::timestamptz <= now() + make_interval(hours => v_hours)
    and nullif(s.creative_brief->>'tracking_url','') is not null
    and (
      lower(s.platform) not in ('instagram','tiktok')
      or nullif(s.creative_brief->>'media_url','') is not null
    )
  on conflict (source_key) do nothing;

  get diagnostics v_inserted = row_count;
  select count(*) into v_pending
  from public.social_publishing_outbox
  where status='queued' and scheduled_for > now();

  return jsonb_build_object('inserted',v_inserted,'pending',v_pending,'horizon_hours',v_hours,'source','vmdb');
end;
$$;

create or replace function public.social_outbox_release_expired_leases()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare v_count integer;
begin
  update public.social_publishing_outbox
     set status='queued', claimed_by=null, claimed_at=null, lease_expires_at=null, provider_key=null
   where status='leased' and lease_expires_at is not null and lease_expires_at < now();
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

create or replace function public.worker_v2_outbox_health()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_released integer;
  v_queued integer;
  v_leased integer;
  v_scheduled integer;
  v_published integer;
  v_failed integer;
begin
  v_released := public.social_outbox_release_expired_leases();
  select
    count(*) filter(where status='queued'),
    count(*) filter(where status='leased'),
    count(*) filter(where status='scheduled'),
    count(*) filter(where status='published'),
    count(*) filter(where status='failed')
  into v_queued,v_leased,v_scheduled,v_published,v_failed
  from public.social_publishing_outbox;
  return jsonb_build_object(
    'source','vmdb','released_expired_leases',v_released,
    'queued',v_queued,'leased',v_leased,'scheduled',v_scheduled,'published',v_published,'failed',v_failed
  );
end;
$$;

create or replace function public.worker_v2_outbox_peek(p_limit integer default 10)
returns setof public.social_publishing_outbox
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.social_outbox_release_expired_leases();
  return query
  select o.*
  from public.social_publishing_outbox o
  where o.status='queued'
    and o.scheduled_for > now()
  order by o.priority asc, o.scheduled_for asc, o.created_at asc
  limit greatest(1,least(coalesce(p_limit,10),50));
end;
$$;

create or replace function public.social_outbox_claim_provider(
  p_provider_key text,
  p_executor text,
  p_capacity jsonb,
  p_lease_minutes integer default 30
)
returns setof public.social_publishing_outbox
language plpgsql
security definer
set search_path = public
as $$
declare
  v_platform text;
  v_limit integer;
  v_lease integer := greatest(5,least(coalesce(p_lease_minutes,30),120));
begin
  if lower(coalesce(p_provider_key,'')) not in ('buffer','postzen','brightbean') then
    raise exception 'invalid_provider';
  end if;
  perform public.social_outbox_release_expired_leases();

  foreach v_platform in array array['facebook','instagram','tiktok','linkedin'] loop
    v_limit := greatest(0,least(coalesce(nullif(p_capacity->>v_platform,'')::integer,0),20));
    if v_limit > 0 then
      return query
      with picked as (
        select o.id
        from public.social_publishing_outbox o
        where o.status='queued'
          and o.platform=v_platform
          and o.scheduled_for > now()
          and (o.provider_key is null or o.provider_key=lower(p_provider_key))
        order by o.priority asc, o.scheduled_for asc, o.created_at asc
        for update skip locked
        limit v_limit
      )
      update public.social_publishing_outbox o
         set status='leased',
             provider_key=lower(p_provider_key),
             claimed_by=coalesce(nullif(p_executor,''),'socialscheduler-'||lower(p_provider_key)),
             claimed_at=now(),
             lease_expires_at=now()+make_interval(mins=>v_lease),
             attempt_count=o.attempt_count+1
      from picked p
      where o.id=p.id
      returning o.*;
    end if;
  end loop;
end;
$$;

