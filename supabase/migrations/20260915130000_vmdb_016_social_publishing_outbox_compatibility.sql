create or replace function public.worker_v11_delivery_reconcile(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid := null;
  v_provider text := lower(coalesce(p_payload->>'provider_key',''));
  v_status text := lower(coalesce(p_payload->>'status',''));
  v_target text;
  v_row public.social_publishing_outbox%rowtype;
begin
  if v_provider not in ('buffer','postzen','brightbean') then raise exception 'invalid_provider'; end if;
  if coalesce(p_payload->>'job_id','') ~* '^[0-9a-f-]{36}$' then v_id := (p_payload->>'job_id')::uuid; end if;
  if v_id is null then raise exception 'job_id_required'; end if;
  v_target := case
    when v_status in ('published','sent','success','succeeded') then 'published'
    when v_status in ('scheduled','queued','pending') then 'scheduled'
    when v_status in ('failed','error','cancelled') then 'failed'
    else null
  end;
  if v_target is null then
    select * into v_row from public.social_publishing_outbox where id=v_id;
    if not found then raise exception 'job_not_found'; end if;
    return to_jsonb(v_row) || jsonb_build_object('reconciliation','unknown_state_no_mutation');
  end if;
  update public.social_publishing_outbox o
     set status=v_target,
         provider_key=v_provider,
         external_post_id=coalesce(nullif(p_payload->>'external_post_id',''),o.external_post_id),
         external_permalink=coalesce(nullif(p_payload->>'external_permalink',''),o.external_permalink),
         published_at=case when v_target='published' then coalesce(nullif(p_payload->>'published_at','')::timestamptz,now()) else o.published_at end,
         last_error=case when v_target='failed' then coalesce(nullif(p_payload->>'error',''),'provider_reconciliation_failed') else null end,
         metadata=o.metadata || jsonb_build_object('last_reconciliation',p_payload),
         claimed_by=null,claimed_at=null,lease_expires_at=null
   where o.id=v_id
   returning o.* into v_row;
  if not found then raise exception 'job_not_found'; end if;
  return to_jsonb(v_row);
end;
$$;

create or replace function public.worker_v2_outbox_import_legacy(p_campaigns jsonb)
returns jsonb
language sql
security definer
set search_path = public
as $$
  -- Deliberately fail-closed after the database reset: old campaigns must not be
  -- silently re-imported and published without fresh verification.
  select jsonb_build_object('imported',0,'skipped',coalesce(jsonb_array_length(p_campaigns),0),'reason','legacy_import_disabled_on_vmdb');
$$;

alter table public.social_publishing_outbox enable row level security;
alter table public.social_distribution_metrics enable row level security;

revoke all on public.social_publishing_outbox from anon, authenticated;
revoke all on public.social_distribution_metrics from anon, authenticated;
grant all on public.social_publishing_outbox to service_role;
grant all on public.social_distribution_metrics to service_role;

do $$
declare f record;
begin
  for f in
    select p.oid::regprocedure as signature
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.proname in (
      'vmdb_social_outbox_refill','social_outbox_release_expired_leases','worker_v2_outbox_health',
      'worker_v2_outbox_peek','social_outbox_claim_provider','socialscheduler_claim_provider_capacity',
      'worker_v3_outbox_claim_capacity','worker_v2_outbox_claim','worker_v3_outbox_refill','worker_v3_outbox_ack',
      'worker_v3_delivery_metrics_batch','worker_v3_optimize_week','worker_v2_outbox_reconcile',
      'socialscheduler_provider_reconcile_candidates','worker_v11_delivery_reconcile','worker_v2_outbox_import_legacy'
    )
  loop
    execute format('revoke all on function %s from public, anon, authenticated',f.signature);
    execute format('grant execute on function %s to service_role',f.signature);
  end loop;
end $$;

